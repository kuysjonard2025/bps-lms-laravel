                    <td>
                        @if ($loan->returned_at && $loan->fine_amount > 0)
                            <span class="text-danger">P{{ number_format((float) $loan->fine_amount, 2) }}</span>
                        @else
                            <span style="color: #94a3b8;">-</span>
                        @endif
                    </td>
                    @endif
